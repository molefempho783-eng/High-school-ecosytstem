"""
Builds the app's icon font from Google's Material Symbols Rounded.

WHY A SUBSET: the full variable font is ~15 MB. The app needs a few dozen
icons, so this pins the variable axes to one style (outlined, weight 400,
24px optical size) and keeps only the icons listed below. The result is a few
KB and draws identically on Windows, Android, iOS and Mac — which system
emoji fonts do not.

TO ADD AN ICON
  1. Find its name at https://fonts.google.com/icons (style: Rounded).
  2. Add  ("PascalName", "icon_name")  to ICONS below.
  3. Run (PowerShell, from the repo root):
        pip install fonttools
        python tools/fonts/build-icon-font.py --source "<path to MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf>"
     It rewrites Resources/Fonts/MaterialSymbolsRounded.ttf and Icons.cs.
  4. Use it as  {x:Static app:Icons.PascalName}  in XAML or  Icons.PascalName  in C#.

SIDEBAR IMAGES
  The navigation rails draw their icons from IMAGES, not this font, so they
  can never go blank if a platform fails to load a font. Pass --svgs to also
  (re)write Resources/Images/rail_<name>.svg for every icon, from the same list:
        python tools/fonts/build-icon-font.py --source "<variable font .ttf>" --svgs "<material-design-icons>/symbols/web"
  The csproj tints rail_*.svg white. Icons.RailImage(glyph) maps a glyph to its
  image, which is how RailItem finds the picture for the codepoint it was given.

The source font and its .codepoints file come from
https://github.com/google/material-design-icons/tree/master/variablefont
Licence: Apache 2.0 (see tools/fonts/MaterialSymbols-LICENSE.txt).
"""
import argparse, pathlib, re
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ICONS = [
    # navigation rail and shared chrome
    ("Menu", "menu"),
    ("Home", "home"),
    ("Account", "account_circle"),
    ("OtherRoles", "switch_account"),
    ("Settings", "settings"),
    ("Admin", "admin_panel_settings"),
    # school content
    ("Announcement", "campaign"),
    ("Sport", "emoji_events"),
    ("Newspaper", "newspaper"),
    ("Edit", "edit"),
    ("Visibility", "visibility"),
    # teaching and learning
    ("Work", "assignment"),
    ("Classes", "class"),
    ("Grades", "grade"),
    ("Timetable", "calendar_month"),
    ("Teaching", "school"),
    ("CourseContent", "library_books"),
    ("Marking", "fact_check"),
    ("Assessment", "timer"),
    ("Chapter", "menu_book"),
    ("Link", "link"),
    ("File", "description"),
    # people
    ("Person", "person"),
    ("Groups", "groups"),
    ("Children", "family_restroom"),
    # status
    ("Warning", "warning"),
    ("Dot", "circle"),
    ("Published", "check_circle"),
    ("Chat", "forum"),
    ("Attach", "attach_file"),
    ("Photo", "image"),
    ("Close", "close"),
]

STYLE = {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 400}

# Symbols that exist in the font but have no standalone SVG: the image uses
# the closest available one instead.
IMAGE_OVERRIDES = {"class": "grid_view"}

def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    p = argparse.ArgumentParser()
    p.add_argument("--source", required=True, help="MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf")
    p.add_argument("--codepoints", help="matching .codepoints file (default: next to --source)")
    p.add_argument("--svgs", help="material-design-icons/symbols/web, to also write the rail images")
    args = p.parse_args()

    source = pathlib.Path(args.source)
    cp_file = pathlib.Path(args.codepoints) if args.codepoints else source.with_suffix(".codepoints")
    codepoints = {}
    for line in cp_file.read_text(encoding="utf-8").splitlines():
        name, _, hexcode = line.partition(" ")
        if hexcode:
            codepoints[name] = int(hexcode, 16)

    missing = [n for _, n in ICONS if n not in codepoints]
    if missing:
        raise SystemExit(f"Not in Material Symbols: {', '.join(missing)}")

    font = instancer.instantiateVariableFont(TTFont(str(source)), STYLE)
    options = subset.Options()
    options.layout_features = []      # no ligatures needed: the app uses codepoints
    options.name_IDs = ["*"]
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=[codepoints[n] for _, n in ICONS])
    sub.subset(font)

    out_font = root / "HighSchoolEcosystem" / "Resources" / "Fonts" / "MaterialSymbolsRounded.ttf"
    font.save(str(out_font))

    lines = [
        "// <auto-generated>",
        "//   Written by tools/fonts/build-icon-font.py. Edit the ICONS list there and",
        "//   re-run it rather than editing this file: the font only contains the",
        "//   icons listed, so a code added here by hand would draw nothing.",
        "// </auto-generated>",
        "",
        "namespace HighSchoolEcosystem;",
        "",
        "/// <summary>",
        "/// Material Symbols codepoints, for any Label whose FontFamily is",
        "/// \"MaterialSymbols\" (the RailGlyph, RowIcon and TileGlyph styles set it).",
        "/// One bundled font rather than system emoji, so every platform draws the",
        "/// same icon in the same style — Android's emoji font made the rail a mix",
        "/// of colour clip-art and missing boxes.",
        "/// </summary>",
        "public static class Icons",
        "{",
    ]
    for pascal, name in ICONS:
        lines.append(f'    /// <summary>{name}</summary>')
        lines.append(f'    public const string {pascal} = "\\u{codepoints[name]:04x}";')
    lines.append("")
    lines.append("    /// <summary>")
    lines.append("    /// The rail image for a glyph: Resources/Images/rail_*.svg, bundled as PNG for")
    lines.append("    /// every platform and tinted white in the csproj. Empty if there isn't one.")
    lines.append("    /// </summary>")
    lines.append("    public static string RailImage(string glyph) => glyph switch")
    lines.append("    {")
    for pascal, name in ICONS:
        lines.append(f'        {pascal} => "rail_{IMAGE_OVERRIDES.get(name, name)}.png",')
    lines.append("        _ => string.Empty")
    lines.append("    };")
    lines.append("}")
    (root / "HighSchoolEcosystem" / "Icons.cs").write_text("\n".join(lines) + "\n", encoding="utf-8")

    if args.svgs:
        images = root / "HighSchoolEcosystem" / "Resources" / "Images"
        for _, name in ICONS:
            svg_name = IMAGE_OVERRIDES.get(name, name)
            src = pathlib.Path(args.svgs) / svg_name / "materialsymbolsrounded" / f"{svg_name}_24px.svg"
            if not src.exists():
                raise SystemExit(f"No SVG for {name} at {src}; add an IMAGE_OVERRIDES entry.")
            (images / f"rail_{svg_name}.svg").write_text(src.read_text(encoding="utf-8"), encoding="utf-8")
        print(f"Wrote {len(ICONS)} rail images to {images}.")
    print(f"Wrote {out_font} ({out_font.stat().st_size // 1024} KB) with {len(ICONS)} icons.")

if __name__ == "__main__":
    main()
